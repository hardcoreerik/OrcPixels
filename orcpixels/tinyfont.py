"""3x5 pixel font for tiny readouts on the 16-row panel (uppercase, digits, . - : / +)."""
from __future__ import annotations

from PIL import Image

_G = {
    "0": "111101101101111", "1": "010110010010111", "2": "111001111100111",
    "3": "111001111001111", "4": "101101111001001", "5": "111100111001111",
    "6": "111100111101111", "7": "111001010010010", "8": "111101111101111",
    "9": "111101111001111",
    "A": "010101111101101", "B": "110101110101110", "C": "011100100100011",
    "D": "110101101101110", "E": "111100110100111", "F": "111100110100100",
    "G": "011100101101011", "H": "101101111101101", "I": "111010010010111",
    "J": "001001001101010", "K": "101101110101101", "L": "100100100100111",
    "M": "101111111101101", "N": "110101101101101", "O": "010101101101010",
    "P": "110101110100100", "Q": "010101101110011", "R": "110101110101101",
    "S": "011100010001110", "T": "111010010010010", "U": "101101101101111",
    "V": "101101101101010", "W": "101101111111101", "X": "101101010101101",
    "Y": "101101010010010", "Z": "111001010100111",
    ".": "000000000000010", "-": "000000111000000", ":": "000010000010000",
    "/": "001001010100100", "+": "000010111010000", " ": "000000000000000",
    "?": "111001011000010",
    # live data screens (2026-10-02)
    "%": "101001010100101", "!": "010010010000010", ",": "000000000010100", "'": "010010000000000",
    "\u00b0": "010101010000000", "<": "001010100010001", ">": "100010001010100", "(": "010100100100010",
    ")": "010001001001010", "*": "000101010101000", "#": "101111101111101", "=": "000111000111000",
    "&": "010101010101011", "_": "000000000000111",
}
GLYPH_W, GLYPH_H, ADVANCE = 3, 5, 4
_NARROW = {".": 2, ":": 2, " ": 2, "!": 2, "'": 2}   # advance for narrow glyphs (drawn in col 1)


def text_width(text: str) -> int:
    w = sum(_NARROW.get(c, ADVANCE) for c in text.upper())
    return max(0, w - 1)


def draw_text(img: Image.Image, x: int, y: int, text: str, color) -> int:
    """Draw text at (x, y) (top-left). Returns x after the last glyph."""
    px = img.load()
    W, H = img.size
    for ch in text.upper():
        g = _G.get(ch, _G["?"])
        narrow = ch in _NARROW
        for r in range(GLYPH_H):
            for c in range(GLYPH_W):
                if g[r * 3 + c] == "1":
                    xx = x + (c - 1 if narrow else c)
                    yy = y + r
                    if 0 <= xx < W and 0 <= yy < H:
                        px[xx, yy] = color
        x += _NARROW.get(ch, ADVANCE)
    return x
